// Builds tracker/studio-sdk.js: @studio/sdk as one classic script that
// publishes window.StudioSDK (D-039). The tracker itself keeps no build step;
// this file is checked in like a vendored library. --check fails if the
// checked-in copy is not what the SDK source builds to (CI runs it).
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../tracker/studio-sdk.js", import.meta.url));
const entry = fileURLToPath(new URL("../../../packages/sdk/src/browser.ts", import.meta.url));

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  globalName: "StudioSDK",
  target: "es2020",
  platform: "browser",
  legalComments: "inline",
  write: false,
  banner: { js: "/* @studio/sdk for classic scripts. Generated by build/bundle-sdk.mjs from packages/sdk: do not edit. */" },
});
const code = result.outputFiles[0].text;

if (process.argv.includes("--check")) {
  const current = readFileSync(out, "utf8");
  if (current !== code) {
    console.error("tracker/studio-sdk.js is out of date: run `pnpm --filter @studio/show-tracker bundle`");
    process.exit(1);
  }
  console.log("tracker/studio-sdk.js is up to date");
} else {
  writeFileSync(out, code);
  console.log(`wrote tracker/studio-sdk.js (${code.length} bytes)`);
}
