#!/usr/bin/env python3
"""Makes the six sample works' pictures (D-174) and writes src/lib/sample-pictures.ts.

Run from workers/studio-api: python3 scripts/sample-pictures.py  (needs Pillow with WebP).
The pictures are drawn from fixed seeds, so the output is the same each time.
"""
import base64, io, random
from PIL import Image, ImageDraw, ImageFilter

PALETTES = [
    ("#1f3a5f", "#e8d8b0", "#c4572e", "#f3efe6"),
    ("#2e4a3b", "#d9c38a", "#8a3b2e", "#ebe6da"),
    ("#3b2f4a", "#e3b9a4", "#d78a3c", "#efe9e1"),
    ("#16324f", "#7fa7b8", "#b5462f", "#e9e2cf"),
    ("#4a3b2a", "#c9a66b", "#2f4f4f", "#e8e1d3"),
    ("#2b2b2b", "#e0c050", "#5c7a8c", "#efeae0"),
]
W, H = 960, 1200


def rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def draw(i):
    r = random.Random(1000 + i)
    pal = [rgb(c) for c in PALETTES[i]]
    img = Image.new("RGB", (W, H), pal[3])
    d = ImageDraw.Draw(img, "RGBA")
    for _ in range(7):
        c = pal[r.randrange(3)]
        x, y = r.randrange(-200, W), r.randrange(-200, H)
        if r.random() < 0.5:
            d.rectangle([x, y, x + r.randrange(200, 700), y + r.randrange(150, 600)], fill=c + (r.randrange(150, 235),))
        else:
            rad = r.randrange(120, 420)
            d.ellipse([x, y, x + rad, y + rad], fill=c + (r.randrange(150, 235),))
    return img.filter(ImageFilter.GaussianBlur(2))


def webp(img):
    b = io.BytesIO()
    img.save(b, "WEBP", quality=72, method=6)
    return base64.b64encode(b.getvalue()).decode()


out = [
    "// Generated by scripts/sample-pictures.py: the sample works' pictures (D-174). Don't edit by hand.",
    "/** Each sample picture: its palette (the four colours drawn) and WebP bytes at 480 and 960 pixels wide, base64. */",
    "export const SAMPLE_PICTURES: { palette: string[]; width: number; height: number; webp: Record<480 | 960, string> }[] = [",
]
for i, pal in enumerate(PALETTES):
    img = draw(i)
    small = img.resize((480, 600), Image.LANCZOS)
    out.append(f'  {{ palette: {list(pal)!r}, width: {W}, height: {H}, webp: {{ 480: "{webp(small)}", 960: "{webp(img)}" }} }},'.replace("'", '"'))
out.append("];")
open("src/lib/sample-pictures.ts", "w").write("\n".join(out) + "\n")
print("wrote src/lib/sample-pictures.ts")
